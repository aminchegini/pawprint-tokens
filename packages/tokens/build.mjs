// Style Dictionary build for @paws/tokens.
//
// Source: figma.tokens.json (DTCG). Three groups: primitive, semantic, legacy.
// Semantic tokens may carry one value per mode under $extensions["paws.modes"];
// $value always holds the default (first) mode.
//
// Output (dist/): tokens.css, theme.css, tokens.ts, legacy-map.json. The output
// is deterministic (no timestamps) because CI rebuilds it and diffs the result.
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const MODES_KEY = 'paws.modes';
const REF = /^\{([^{}]+)\}$/;
const HEADER = 'Generated by Style Dictionary from figma.tokens.json. Do not edit.';

// Style Dictionary resolves references in place, so formats read the untouched
// source: that is where per-mode references and alias targets still exist.
const source = JSON.parse(readFileSync(here('./figma.tokens.json'), 'utf8'));
const { $metadata: _metadata, ...tokenTree } = structuredClone(source);

// ---- helpers ---------------------------------------------------------------

const layer = (token) => token.path[0];
const dotName = (token) => token.path.slice(1).join('.');
const cssVar = (name) => `--${name.replaceAll('.', '-')}`;
const refTarget = (value) => (typeof value === 'string' ? value.match(REF)?.[1] : undefined);
const lookup = (path) => path.reduce((node, key) => node?.[key], source);
/** The token as written in figma.tokens.json, references unresolved. */
const raw = (token) => lookup(token.path);

/** Follow {a.b.c} references through the raw source until a literal value. */
function resolve(value, mode, seen = []) {
  const target = refTarget(value);
  if (!target) return value;
  if (seen.includes(target)) throw new Error(`Circular reference: ${[...seen, target].join(' -> ')}`);
  const token = lookup(target.split('.'));
  if (!token || !('$value' in token)) throw new Error(`Unresolved reference {${target}}`);
  const next = token.$extensions?.[MODES_KEY]?.[mode] ?? token.$value;
  return resolve(next, mode, [...seen, target]);
}

function collectModes(tokens) {
  const modes = [];
  for (const token of tokens) {
    for (const mode of Object.keys(raw(token).$extensions?.[MODES_KEY] ?? {})) {
      if (!modes.includes(mode)) modes.push(mode);
    }
  }
  if (modes.length === 0) throw new Error('No modes found in semantic tokens');
  return modes;
}

/** The layer model, enforced: semantic -> primitive, legacy -> semantic. */
function validate(tokens, modes) {
  const problems = [];
  for (const token of tokens) {
    const name = token.path.join('.');
    const { $value, $deprecated, $extensions } = raw(token);
    const byMode = $extensions?.[MODES_KEY];
    const values = byMode ? Object.values(byMode) : [$value];
    if (layer(token) === 'semantic') {
      if (byMode) {
        const missing = modes.filter((mode) => !(mode in byMode));
        if (missing.length) problems.push(`${name}: missing mode(s) ${missing.join(', ')}`);
      }
      for (const value of values) {
        if (!refTarget(value)?.startsWith('primitive.')) problems.push(`${name}: ${value} is not a primitive reference`);
      }
    }
    if (layer(token) === 'legacy') {
      if (!refTarget($value)?.startsWith('semantic.')) problems.push(`${name}: must alias a semantic token`);
      if (!$deprecated) problems.push(`${name}: missing $deprecated note`);
    }
  }
  if (problems.length) throw new Error(`Token layer violations:\n  ${problems.join('\n  ')}`);
}

function model(dictionary) {
  const semantic = dictionary.allTokens.filter((t) => layer(t) === 'semantic');
  const legacy = dictionary.allTokens.filter((t) => layer(t) === 'legacy');
  const modes = collectModes(semantic);
  validate(dictionary.allTokens, modes);
  /** Literal value of a semantic token in one mode. */
  const value = (token, mode) => {
    const { $value, $extensions } = raw(token);
    return resolve($extensions?.[MODES_KEY]?.[mode] ?? $value, mode);
  };
  /** Semantic name a legacy alias points at, without the layer prefix. */
  const target = (token) => refTarget(raw(token).$value).replace(/^semantic\./, '');
  return { semantic, legacy, modes, value, target };
}

// ---- Style Dictionary extensions -------------------------------------------

StyleDictionary.registerTransform({
  name: 'paws/name',
  type: 'name',
  transform: (token) =>
    (layer(token) === 'primitive' ? token.path : token.path.slice(1)).join('-'),
});

// tokens.css: semantic and legacy custom properties, one block per mode.
StyleDictionary.registerFormat({
  name: 'paws/css-modes',
  format: ({ dictionary }) => {
    const { semantic, legacy, modes, value, target } = model(dictionary);
    const blocks = modes.map((mode, i) => {
      const selector = i === 0 ? `:root,\n[data-skin="${mode}"]` : `[data-skin="${mode}"]`;
      const lines = [
        ...semantic.map((t) => `  ${cssVar(dotName(t))}: ${value(t, mode)};`),
        '',
        '  /* Deprecated aliases. Migrate with @paws/codemod. */',
        ...legacy.map((t) => `  ${cssVar(dotName(t))}: var(${cssVar(target(t))});`),
      ];
      return `${selector} {\n${lines.join('\n')}\n}`;
    });
    return `/* ${HEADER} */\n\n${blocks.join('\n\n')}\n`;
  },
});

// theme.css: Tailwind v4 theme. Semantic names only; the default colour palette
// is cleared so neither primitives nor Tailwind's own ramps are reachable.
const TAILWIND_NAMESPACE = [
  ['color.', '--color-'],
  ['space.', '--spacing-'],
  ['radius.', '--radius-'],
  ['font.size.', '--text-'],
];

StyleDictionary.registerFormat({
  name: 'paws/tailwind-theme',
  format: ({ dictionary }) => {
    const { semantic, modes, value } = model(dictionary);
    const lines = [];
    for (const token of semantic) {
      const name = dotName(token);
      const mapping = TAILWIND_NAMESPACE.find(([prefix]) => name.startsWith(prefix));
      if (!mapping) throw new Error(`No Tailwind namespace for semantic token ${name}`);
      const themeVar = mapping[1] + name.slice(mapping[0].length).replaceAll('.', '-');
      // A theme variable that shares its name with the semantic custom property
      // takes the default-mode value (a self-reference would be a cycle); the
      // mode blocks in tokens.css override it at runtime. Renamed ones alias.
      const themeValue = themeVar === cssVar(name) ? value(token, modes[0]) : `var(${cssVar(name)})`;
      lines.push(`  ${themeVar}: ${themeValue};`);
    }
    return [
      `/* ${HEADER} */`,
      '/* Tailwind v4 theme. Import after "tailwindcss" and next to tokens.css. */',
      '',
      '@theme {',
      '  --color-*: initial;',
      ...lines,
      '}',
      '',
    ].join('\n');
  },
});

// tokens.ts: typed map tokens[mode][name], plus a number helper for three.js.
StyleDictionary.registerFormat({
  name: 'paws/typescript',
  format: ({ dictionary }) => {
    const { semantic, modes, value } = model(dictionary);
    const q = (s) => `'${s}'`;
    const maps = modes.map((mode) => {
      const entries = semantic.map((t) => `    ${q(dotName(t))}: ${q(value(t, mode))},`);
      return `  ${mode}: {\n${entries.join('\n')}\n  },`;
    });
    return `// ${HEADER}

export const modes = [${modes.map(q).join(', ')}] as const;

export type Mode = (typeof modes)[number];

export const defaultMode: Mode = ${q(modes[0])};

/** Semantic tokens per mode. Colours are hex strings, dimensions are px strings. */
export const tokens = {
${maps.join('\n')}
} as const;

export type TokenName = keyof (typeof tokens)[Mode];

export type ColorTokenName = Extract<TokenName, \`color.\${string}\`>;

/** The CSS custom property that carries a token, for example "--color-surface-page". */
export function cssVar(name: TokenName): string {
  return \`--\${name.replaceAll('.', '-')}\`;
}

/** A colour token as a number (0xrrggbb), the form three.js materials take. */
export function colorNumber(mode: Mode, name: ColorTokenName): number {
  return Number.parseInt(tokens[mode][name].slice(1, 7), 16);
}
`;
  },
});

// legacy-map.json: deprecated name -> semantic name. Input for @paws/codemod.
StyleDictionary.registerFormat({
  name: 'paws/legacy-map',
  format: ({ dictionary }) => {
    const { legacy, target } = model(dictionary);
    const map = Object.fromEntries(legacy.map((t) => [dotName(t), target(t)]));
    return `${JSON.stringify(map, null, 2)}\n`;
  },
});

// ---- build -----------------------------------------------------------------

const sd = new StyleDictionary({
  tokens: tokenTree,
  usesDtcg: true,
  platforms: {
    paws: {
      transforms: ['paws/name'],
      buildPath: here('./dist/'),
      files: [
        { destination: 'tokens.css', format: 'paws/css-modes' },
        { destination: 'theme.css', format: 'paws/tailwind-theme' },
        { destination: 'tokens.ts', format: 'paws/typescript' },
        { destination: 'legacy-map.json', format: 'paws/legacy-map' },
      ],
    },
  },
});

await sd.buildAllPlatforms();
